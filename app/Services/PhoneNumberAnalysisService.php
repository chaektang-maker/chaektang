    private function getTotalSumMeaning(int $sum): array
    {
        $excellentSums = [24, 36, 40, 41, 42, 44, 45, 46, 50, 51, 54, 55, 56, 59, 60, 63, 64, 65, 69];
        $goodSums = [14, 15, 19, 23, 26, 28, 29, 32, 35, 39, 47, 49, 52, 53, 58, 62, 66, 68, 78, 79, 89];

        if (in_array($sum, $excellentSums, true)) {
            return [
                'level' => 'excellent',
                'score' => 95,
                'title' => "ผลรวม {$sum} — มหามงคลหนุนทรัพย์และบารมี",
                'meaning' => 'ผลรวมเบอร์อยู่ในเกณฑ์ดีเยี่ยมสูงสุด ส่งเสริมให้ชีวิตพบเจอความสำเร็จ มีโชคลาภทางการเงิน และมีคนคอยสนับสนุนช่วยเหลือเสมอ',
            ];
        }

        if (in_array($sum, $goodSums, true)) {
            return [
                'level' => 'good',
                'score' => 84,
                'title' => "ผลรวม {$sum} — พลังความก้าวหน้าและโชคลาภ",
                'meaning' => 'ผลรวมเบอร์อยู่ในเกณฑ์ดี ช่วยหนุนให้การทำมาค้าขายและการงานประสบความสำเร็จ มีโอกาสรับโชคลาภเป็นระยะ',
            ];
        }

        return [
            'level' => 'neutral',
            'score' => 66,
            'title' => "ผลรวม {$sum} — พลังนักสู้ผู้สร้างฐานะด้วยตนเอง",
            'meaning' => 'ผลรวมเบอร์เน้นความขยันและอดทน อาจต้องเหนื่อยบุกเบิกด้วยตัวเองก่อนแล้วจึงจะพบความมั่นคงในภายหลัง แนะนำให้พกวัตถุมงคลช่วยเสริมดวงโชคลาภ',
        ];
    }
