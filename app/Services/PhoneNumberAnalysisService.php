    public function getLevelLabel(string $level): string
    {
        return match ($level) {
            'excellent' => '⭐ มงคลสูงสุด',
            'good' => '✅ คู่เลขมงคล',
            'neutral' => '⚖️ ปานกลาง',
            default => '⚠️ ควรระวัง/แก้เคล็ด',
        };
    }

    /**
     * โหลดข้อมูลคู่เลขที่แอดมินปรับแต่งไว้ใน Database (ถ้ามี)
     * หากไม่ได้บันทึกไว้ใน Database ระบบจะใช้ตำรามาตรฐานในโค้ดโดยอัตโนมัติ (ทำงานคู่กัน 100%)
     */
    private function getDbOverrides(): array
    {
        if ($this->dbOverridesCache !== null) {
            return $this->dbOverridesCache;
        }

        try {
            if (!Schema::hasTable('phone_pair_meanings')) {
                $this->dbOverridesCache = [];
                return [];
            }

            $rows = PhonePairMeaning::all();
            $map = [];
            foreach ($rows as $row) {
                $map[$row->pair] = [
                    'level' => $row->level,
                    'score' => (int) $row->score,
                    'title' => $row->title,
                    'meaning' => $row->meaning,
                    'aspects' => [
                        'wealth' => (int) $row->wealth_score,
                        'career' => (int) $row->career_score,
                        'charm' => (int) $row->charm_score,
                        'health' => (int) $row->health_score,
                    ],
                    'is_custom' => true,
                    'updated_at' => $row->updated_at?->format('Y-m-d H:i'),
                ];
            }

            $this->dbOverridesCache = $map;
            return $map;
        } catch (\Throwable $e) {
            $this->dbOverridesCache = [];
            return [];
        }
    }

    /**
     * ดึงความหมายคู่เลข (เช็กจาก Database ก่อน ถ้าไม่มีให้ใช้ค่ามาตรฐานจากตำราในโค้ด)
     */
    public function getPairMeaning(string $pair): array
    {
        $overrides = $this->getDbOverrides();
        if (isset($overrides[$pair])) {
            return $overrides[$pair];
        }

        return $this->getDefaultPairMeaning($pair);
    }

