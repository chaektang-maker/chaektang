     * ดึงรายการคู่เลขทั้งหมด 00-99 พร้อมสถานะว่าคู่ไหนใช้ค่ามาตรฐาน หรือปรับแต่งเองใน Database
     */
    public function getAllPairsForAdmin(): array
    {
        $overrides = $this->getDbOverrides();
        $list = [];

        for ($i = 0; $i <= 99; $i++) {
            $pair = str_pad((string) $i, 2, '0', STR_PAD_LEFT);
            $default = $this->getDefaultPairMeaning($pair);
            $current = $overrides[$pair] ?? $default;

            $list[] = [
                'pair' => $pair,
                'level' => $current['level'],
                'level_label' => $this->getLevelLabel($current['level']),
                'score' => $current['score'],
                'title' => $current['title'],
                'meaning' => $current['meaning'],
                'wealth_score' => $current['aspects']['wealth'],
                'career_score' => $current['aspects']['career'],
                'charm_score' => $current['aspects']['charm'],
                'health_score' => $current['aspects']['health'],
                'is_custom' => isset($overrides[$pair]),
                'updated_at' => $overrides[$pair]['updated_at'] ?? null,
                'default_title' => $default['title'],
                'default_meaning' => $default['meaning'],
                'default_level' => $default['level'],
                'default_score' => $default['score'],
            ];
        }

        return $list;
    }

