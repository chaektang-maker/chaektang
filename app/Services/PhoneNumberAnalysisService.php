    /**
     * วิเคราะห์เบอร์โทรศัพท์มือถือ 10 หลัก ตามหลักเลขศาสตร์เบอร์มงคลมาตรฐานไทย
     * (วิเคราะห์ 6 คู่ลำดับจาก 7 ตัวท้าย + ผลรวมทั้ง 10 หลัก + กราฟพลัง 4 ด้าน + เลขนำโชคเชื่อมกับสำนักหวย)
     */
    public function analyze(string $rawPhone): array
    {
        $clean = preg_replace('/\D/', '', $rawPhone) ?? '';

        if (!preg_match('/^0[689]\d{8}$/', $clean)) {
            return [
                'success' => false,
                'error' => 'กรุณากรอกเบอร์โทรศัพท์มือถือ 10 หลักให้ถูกต้อง (ขึ้นต้นด้วย 06, 08 หรือ 09)',
            ];
        }

        $formattedPhone = substr($clean, 0, 3) . '-' . substr($clean, 3, 3) . '-' . substr($clean, 6, 4);
        $digits = array_map('intval', str_split($clean));
        $totalSum = array_sum($digits);

        // ตัด 7 ตัวท้ายมาแยกเป็น 6 คู่ลำดับ (หลักที่ 4-10)
        // น้ำหนักความสำคัญ: คู่ท้ายสุดสำคัญที่สุดตามหลักเลขศาสตร์เบอร์มงคล
        $weights = [1.0, 1.0, 1.15, 1.25, 1.4, 1.5];
        $positionNames = [
            'คู่ที่ 1 (บุคลิกภาพภายนอก)',
            'คู่ที่ 2 (ความคิดและการติดต่อ)',
            'คู่ที่ 3 (การงานและสังคม)',
            'คู่ที่ 4 (การเงินและโชคลาภ)',
            'คู่ที่ 5 (เสน่ห์และครอบครัว)',
            'คู่ที่ 6 (บทสรุปชีวิตและทรัพย์สิน)',
        ];

        $pairsAnalysis = [];
        $weightedScoreSum = 0.0;
        $totalWeight = array_sum($weights);

        $aspectTotals = [
            'wealth' => 0.0,
            'career' => 0.0,
            'charm' => 0.0,
            'health' => 0.0,
        ];

        $badPairs = [];
        $goodPairs = [];

        for ($i = 0; $i < 6; $i++) {
            $pairStr = substr($clean, 3 + $i, 2);
            $meta = $this->getPairMeaning($pairStr);
            $w = $weights[$i];

            $weightedScoreSum += $meta['score'] * $w;
            $aspectTotals['wealth'] += $meta['aspects']['wealth'] * $w;
            $aspectTotals['career'] += $meta['aspects']['career'] * $w;
            $aspectTotals['charm'] += $meta['aspects']['charm'] * $w;
            $aspectTotals['health'] += $meta['aspects']['health'] * $w;

            if ($meta['level'] === 'bad') {
                $badPairs[] = $pairStr;
            } elseif (in_array($meta['level'], ['excellent', 'good'], true)) {
                $goodPairs[] = $pairStr;
            }

            $pairsAnalysis[] = [
                'position' => $i + 1,
                'position_label' => $positionNames[$i],
                'pair' => $pairStr,
                'title' => $meta['title'],
                'meaning' => $meta['meaning'],
                'level' => $meta['level'], // excellent, good, neutral, bad
                'level_label' => $this->getLevelLabel($meta['level']),
                'score' => $meta['score'],
            ];
        }

        // คะแนนผลรวม 10 หลัก (คิดเป็น 15% ของคะแนนรวม)
        $sumMeta = $this->getTotalSumMeaning($totalSum);
        $pairAvgScore = $weightedScoreSum / $totalWeight;
        $overallScore = (int) round(($pairAvgScore * 0.85) + ($sumMeta['score'] * 0.15));

        // หากมีคู่เลขเสียรุนแรงในช่วง 2 คู่ท้าย ให้ปรับเพดานคะแนนตามหลักเลขศาสตร์จริง
        $tailBadCount = 0;
        if ($pairsAnalysis[4]['level'] === 'bad') {
            $tailBadCount++;
        }
        if ($pairsAnalysis[5]['level'] === 'bad') {
            $tailBadCount++;
        }
        if ($tailBadCount > 0) {
            $overallScore = max(35, $overallScore - ($tailBadCount * 7));
        }

        $overallScore = max(25, min(99, $overallScore));

        $aspects = [
            'wealth' => (int) max(25, min(99, round($aspectTotals['wealth'] / $totalWeight))),
            'career' => (int) max(25, min(99, round($aspectTotals['career'] / $totalWeight))),
            'charm' => (int) max(25, min(99, round($aspectTotals['charm'] / $totalWeight))),
            'health' => (int) max(25, min(99, round($aspectTotals['health'] / $totalWeight))),
        ];

        $gradeInfo = $this->calculateGrade($overallScore, count($badPairs));
        $luckyNumbers = $this->deriveLuckyNumbers($clean, $totalSum, $goodPairs);
        $remedyAdvice = $this->buildRemedyAdvice($badPairs, $goodPairs, $aspects);

        return [
            'success' => true,
            'phone' => $clean,
            'formatted_phone' => $formattedPhone,
            'overall_score' => $overallScore,
            'grade' => $gradeInfo['grade'],
            'grade_title' => $gradeInfo['title'],
            'grade_summary' => $gradeInfo['summary'],
            'grade_color' => $gradeInfo['color'],
            'total_sum' => [
                'number' => $totalSum,
                'title' => $sumMeta['title'],
                'meaning' => $sumMeta['meaning'],
                'level' => $sumMeta['level'],
                'level_label' => $this->getLevelLabel($sumMeta['level']),
            ],
            'aspects' => $aspects,
            'pairs' => $pairsAnalysis,
            'bad_pairs' => array_values(array_unique($badPairs)),
            'good_pairs' => array_values(array_unique($goodPairs)),
            'remedy_advice' => $remedyAdvice,
            'lucky_numbers' => $luckyNumbers,
        ];
    }

    /**
     * ถอดรหัสเลขนำโชคจากเบอร์มือถือ และตรวจสอบว่าตรงกับสำนักหวยงวดล่าสุดกี่สำนัก
     */
    private function deriveLuckyNumbers(string $cleanPhone, int $totalSum, array $goodPairs): array
    {
        $twoDigits = [];

        // 1. นำผลรวม 2 หลักมาเป็นเลขนำโชคตัวแรก
        $sumStr = str_pad((string) ($totalSum % 100), 2, '0', STR_PAD_LEFT);
        $twoDigits[] = $sumStr;

        // 2. นำคู่เลขมงคลในเบอร์มาเป็นเลขนำโชค
        foreach (array_reverse($goodPairs) as $gp) {
            if (!in_array($gp, $twoDigits, true)) {
                $twoDigits[] = $gp;
            }
        }

        // 3. นำ 2 ตัวท้ายและ 3 ตัวท้ายของเบอร์มือถือมาด้วยเสมอ
        $lastTwo = substr($cleanPhone, -2);
        $lastThree = substr($cleanPhone, -3);
        if (!in_array($lastTwo, $twoDigits, true)) {
            $twoDigits[] = $lastTwo;
        }

        $twoDigits = array_slice($twoDigits, 0, 4);

        // สร้างเลข 3 ตัวมงคลจากเบอร์
        $threeDigits = [$lastThree];
        $midThree = substr($cleanPhone, 4, 3);
        if ($midThree !== $lastThree) {
            $threeDigits[] = $midThree;
        }

        // ตรวจสอบว่าเลข 2 ตัวในเบอร์ ตรงกับแนวทางของสำนักหวยในงวดล่าสุดหรือไม่
        $matchingSourcesCount = 0;
        $latestDrawDate = LotteryNumber::max('draw_date');
        if ($latestDrawDate && !empty($twoDigits)) {
            $matchingSourcesCount = LotteryNumber::where('draw_date', $latestDrawDate)
                ->whereIn('two_digit', $twoDigits)
                ->count();
        }

        return [
            'two_digits' => $twoDigits,
            'three_digits' => $threeDigits,
            'matching_sources_count' => $matchingSourcesCount,
        ];
    }

